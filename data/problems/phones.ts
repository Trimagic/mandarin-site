const directionSlug = phoneRepairData.slug;
const href = (slug: string) => getDirectionItemHref(directionSlug, slug);

function enquiry(message: string) {
  return `${phoneRepairData.hero.secondaryAction.href}?text=${encodeURIComponent(message)}`;
}

function breadcrumbs(label: string, slug: string) {
  return [...phoneRepairData.breadcrumbs, { label, href: href(slug) }];
}

function hero(title: string, accent: string, description: string, problem: string): ProblemPageData["hero"] {
  return {
    title,
    accent,
    description,
    image: phoneRepairData.hero.image,
    backgrounds: phoneRepairData.hero.backgrounds,
    primaryAction: { label: "Узнать стоимость", href: enquiry(`Здравствуйте! ${problem}. Хочу уточнить стоимость диагностики и ремонта. Моя модель: `) },
    secondaryAction: phoneRepairData.hero.secondaryAction,
    benefits: [
      { title: "Диагностика при ремонте — бесплатно", description: "", icon: "diagnostics" },
      { title: "Цена до ремонта", description: "", icon: "price" },
      { title: "Гарантия на работы", description: "", icon: "shield" },
    ],
  };
}

function diagnosticsPrice(problem: string) {
  return { id: "diagnostics", title: "Диагностика", price: "Бесплатно при ремонте", action: { label: "Записаться", href: enquiry(`Здравствуйте! ${problem}. Хочу записаться на диагностику. Моя модель: `) } };
}

function process(first: string, second: string) {
  return {
    title: "Как проходит ремонт",
    items: [
      { title: "Обращение", text: first },
      { title: "Диагностика", text: second },
      { title: "Согласование", text: "Обсуждаем необходимые работы, стоимость и сроки ремонта." },
      { title: "Ремонт и выдача", text: "Выполняем ремонт и проверяем телефон перед выдачей." },
    ],
  };
}

