const directionSlug = phoneRepairData.slug;
const href = (slug: string) => getDirectionItemHref(directionSlug, slug);

function enquiry(message: string) {
  return `${phoneRepairData.hero.secondaryAction.href}?text=${encodeURIComponent(message)}`;
}

function modelEnquiry(subject: string) {
  return enquiry(`Здравствуйте! Интересует ${subject}. Моя модель телефона: `);
}

function breadcrumbs(label: string, slug: string) {
  return [...phoneRepairData.breadcrumbs, { label, href: href(slug) }];
}

function hero(title: string, accent: string, description: string, subject: string, price: string, image?: ServicePageData["hero"]["image"]): ServicePageData["hero"] {
  return {
    title,
    accent,
    description,
    image: image ?? phoneRepairData.hero.image,
    backgrounds: phoneRepairData.hero.backgrounds,
    primaryAction: { label: "Узнать стоимость", href: enquiry(`Здравствуйте! Хочу узнать стоимость: ${subject}. Моя модель телефона: `) },
    secondaryAction: phoneRepairData.hero.secondaryAction,
    benefits: [
      { title: price, description: "", icon: "price" },
      { title: "Диагностика при ремонте — бесплатно", description: "", icon: "diagnostics" },
      { title: "Гарантия на работы", description: "", icon: "shield" },
    ],
  };
}

